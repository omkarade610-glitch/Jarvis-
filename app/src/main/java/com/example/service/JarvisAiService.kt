package com.example.service

import android.graphics.Bitmap
import android.util.Log
import com.google.firebase.Firebase
import com.google.firebase.ai.GenerativeModel
import com.google.firebase.ai.ai
import com.google.firebase.ai.type.ImagePart
import com.google.firebase.ai.type.ResponseModality
import com.google.firebase.ai.type.content
import com.google.firebase.ai.type.generationConfig
import kotlinx.coroutines.CancellationException
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.flow.Flow
import kotlinx.coroutines.flow.flow
import kotlinx.coroutines.withContext
import kotlinx.coroutines.withTimeout

class JarvisAiService {
    private val TAG = "JarvisAiService"

    // Primary text/reasoning model (Gemini 3.8 Flash)
    private val flashModel: GenerativeModel by lazy {
        Firebase.ai.generativeModel(
            modelName = "gemini-3.8-flash",
            generationConfig = generationConfig {
                temperature = 0.7f
            }
        )
    }

    // Image generation model (Gemini Nano Banana 2.1)
    private val imageModel: GenerativeModel by lazy {
        Firebase.ai.generativeModel(
            modelName = "gemini-nano-banana-2.1",
            generationConfig = generationConfig {
                responseModalities = listOf(ResponseModality.IMAGE)
            }
        )
    }

    suspend fun generateResponse(
        prompt: String,
        systemContext: String = ""
    ): Result<String> = withContext(Dispatchers.IO) {
        try {
            val fullPrompt = if (systemContext.isNotBlank()) {
                "$systemContext\n\nUser request: $prompt"
            } else {
                prompt
            }

            val response = withTimeout(60_000L) {
                flashModel.generateContent(fullPrompt)
            }
            val text = response.text
            if (!text.isNullOrBlank()) {
                Result.success(text)
            } else {
                Result.failure(IllegalStateException("JARVIS received an empty response."))
            }
        } catch (e: CancellationException) {
            throw e
        } catch (e: Exception) {
            Log.e(TAG, "AI text generation failed", e)
            Result.failure(e)
        }
    }

    fun generateStreamResponse(
        prompt: String,
        systemContext: String = ""
    ): Flow<String> = flow {
        val fullPrompt = if (systemContext.isNotBlank()) {
            "$systemContext\n\nUser request: $prompt"
        } else {
            prompt
        }

        withTimeout(60_000L) {
            flashModel.generateContentStream(fullPrompt).collect { chunk ->
                val chunkText = chunk.text.orEmpty()
                if (chunkText.isNotEmpty()) {
                    emit(chunkText)
                }
            }
        }
    }

    suspend fun generateImage(
        prompt: String,
        aspectRatio: String = "1:1"
    ): Result<Bitmap> = withContext(Dispatchers.IO) {
        try {
            val response = withTimeout(60_000L) {
                imageModel.generateContent(prompt)
            }
            val imagePart = response.candidates.firstOrNull()
                ?.content?.parts?.filterIsInstance<ImagePart>()
                ?.firstOrNull()

            val bitmap = imagePart?.image
            if (bitmap != null) {
                Result.success(bitmap)
            } else {
                Result.failure(IllegalStateException("No image generated by model."))
            }
        } catch (e: CancellationException) {
            throw e
        } catch (e: Exception) {
            Log.e(TAG, "AI image generation failed", e)
            Result.failure(e)
        }
    }

    suspend fun analyzeImageWithPrompt(
        bitmap: Bitmap,
        prompt: String
    ): Result<String> = withContext(Dispatchers.IO) {
        try {
            val response = withTimeout(60_000L) {
                flashModel.generateContent(
                    content {
                        image(bitmap)
                        text(prompt)
                    }
                )
            }
            val text = response.text
            if (!text.isNullOrBlank()) {
                Result.success(text)
            } else {
                Result.failure(IllegalStateException("Empty image analysis returned."))
            }
        } catch (e: CancellationException) {
            throw e
        } catch (e: Exception) {
            Log.e(TAG, "Multimodal generation failed", e)
            Result.failure(e)
        }
    }
}
